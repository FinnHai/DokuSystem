/** Avatar mit Initialen */
export function Avatar({ name, size = "w-9 h-9" }: { name: string; size?: string }) {
  const initials = name
    .split(/\s+/)
    .map((p) => p[0])
    .slice(0, 2)
    .join("")
    .toUpperCase();
  return (
    <div className={`${size} rounded-full bg-gradient-to-br from-primary to-secondary text-primary-content flex items-center justify-center text-xs font-bold shrink-0`}>
      {initials}
    </div>
  );
}
